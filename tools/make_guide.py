"""Turn a guide JSON file into DruidKit_Guide.lua for the in-game guide window.

Usage: python3 tools/make_guide.py tools/example_guide.json DruidKit/DruidKit_Guide.lua

guide.json:
{
  "title": str, "updated": str,
  "tabs": [{"name": str, "sections": [section, ...]}, ...]
}
section:
{
  "title": str,
  "lines": [str, ...],
  "icon": str,                                   optional
  "short": str,                                  optional jump-button label (10 chars max)
  "go": {"zone": str, "x": num, "y": num, "label": str}   optional Go button (map coordinates 0-100)
}
"route" (optional): the step tracker's route, see tools/example_route.py and DruidKit_Steps.lua
}
Icons are names from Interface\\Icons (e.g. "Ability_Racial_BearForm").
Lines starting with "- " become green bullets. WoW colour codes (|cffRRGGBB...|r) are allowed.
"""

import json
import sys


def lua_str(s: str) -> str:
    """Quote s as a Lua long string, picking a [==[ level that the text itself never contains."""
    level = 0
    while ("]" + "=" * level + "]") in s:
        level += 1
    eq = "=" * level
    return f"[{eq}[{s}]{eq}]"


def lua_value(v):
    """Python value -> Lua literal (strings, numbers, booleans, lists)."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return lua_str(v)
    if isinstance(v, list):
        return "{ " + ", ".join(lua_value(x) for x in v) + " }"
    raise TypeError(f"can't write {type(v).__name__} to Lua")


# Route step keys as the addon reads them ("goto" is a Lua 5.2+ keyword, so it becomes "at").
STEP_KEYS = {"do": '["do"]', "goto": "at"}


def route_lua(route) -> list:
    """DruidKitRoute = { id = ..., sections = { { title = ..., steps = { {...}, ... } } } }"""
    if not route:
        return ["DruidKitRoute = nil"]
    out = ["DruidKitRoute = {", f"  id = {lua_str(route['id'])},", "  sections = {"]
    for sec in route["sections"]:
        out.append(f"    {{ title = {lua_str(sec['title'])}, steps = {{")
        for st in sec["steps"]:
            fields = ", ".join(f"{STEP_KEYS.get(k, k)} = {lua_value(v)}" for k, v in st.items())
            out.append(f"      {{ {fields} }},")
        out.append("    } },")
    out.append("  },")
    # Bag plan for quest items needed later (tools/item_plan.py): name -> { action = bank|drop|keep, why = ... }
    items = route.get("items") or {}
    if items:
        out.append("  items = {")
        for name, it in items.items():
            # space after "[": a long string ([[...]]) right after "[" would read as "[[["
            out.append(f"    [ {lua_str(name)} ] = {{ action = {lua_str(it['action'])}, why = {lua_str(it['why'])} }},")
        out.append("  },")
    out.append("}")
    return out


def main(src: str, dest: str) -> None:
    with open(src, encoding="utf-8") as f:
        g = json.load(f)
    out = ["-- Generated by tools/make_guide.py. Do not edit by hand; regenerate and /reload.", "DruidKitGuide = {"]
    out.append(f"  title = {lua_str(g['title'])},")
    out.append(f"  updated = {lua_str(g['updated'])},")
    out.append("  tabs = {")
    for tab in g["tabs"]:
        out.append("    {")
        out.append(f"      name = {lua_str(tab['name'])},")
        out.append("      sections = {")
        for s in tab["sections"]:
            out.append("        {")
            out.append(f"          title = {lua_str(s['title'])},")
            if s.get("short"):
                out.append(f"          short = {lua_str(s['short'])},")
            if s.get("icon"):
                out.append(f"          icon = {lua_str(s['icon'])},")
            if s.get("go"):
                go = s["go"]
                out.append(
                    f"          go = {{ zone = {lua_str(go['zone'])}, x = {float(go['x'])}, y = {float(go['y'])}, "
                    f"label = {lua_str(go.get('label', ''))} }},"
                )
            out.append("          lines = {")
            for line in s["lines"]:
                out.append(f"            {lua_str(line)},")
            out.append("          },")
            out.append("        },")
        out.append("      },")
        out.append("    },")
    out.append("  },")
    out.append("}")
    out.extend(route_lua(g.get("route")))
    # Vendors near the route (rk.py vendors): the step tracker names the nearest one when your bags fill up.
    vendors = g.get("vendors") or []
    out.append("DruidKitVendors = {")
    for z, x, y, name, what, repair in vendors:
        row = [lua_str(z), str(float(x)), str(float(y)), lua_str(name), lua_str(what), lua_value(bool(repair))]
        out.append("  { " + ", ".join(row) + " },")
    out.append("}")
    with open(dest, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
