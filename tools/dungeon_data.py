"""Generate DruidKit/DruidKit_DungeonData.lua: every Alliance dungeon quest (Night Elf druid), with level, XP,
quest giver and spot, and the quests that must be done first. Read by DruidKit_Dungeons.lua (/dk dq, quest share).

Usage: python3 tools/dungeon_data.py [OUT.lua]
Data: planner/db.json (QuestieDB Forever), XP from Questie's tables (Forever traces over Classic) and the
published Forever values in planner/rk.py. The output is derived from QuestieDB (GPLv3): see NOTICE.
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "planner"))
import rk  # noqa: E402
from make_guide import lua_str  # noqa: E402

HEADER = [
    "-- Generated by tools/dungeon_data.py. Do not edit by hand.",
    "-- Source: QuestieDB (https://github.com/Questie/Questie), WoW Forever quest, NPC and XP data.",
    "-- Derived from GPLv3-licensed data; see NOTICE.",
]
DUNGEONS = {  # zoneOrSort -> name (new Forever dungeons by the quests they hold)
    1581: "The Deadmines",
    718: "Wailing Caverns",
    717: "The Stockade",
    209: "Shadowfang Keep",
    719: "Blackfathom Deeps",
    133: "Gnomeregan",
    1717: "Razorfen Kraul",
    16732: "Excavation Site: Wetlands",
    796: "Scarlet Monastery",
    722: "Razorfen Downs",
    1337: "Uldaman",
    16611: "Ruins of Lordaeron",
    16919: "The Hall of Thanes",
}
ALLIANCE = 4294967373
NIGHT_ELF = 8


def lua(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return lua_str(v)
    if isinstance(v, list):
        return "{" + ", ".join(lua(x) for x in v) + "}"
    if v is None:
        return "nil"
    raise TypeError(v)


def build():
    db = rk.db()
    out = {}
    for k, q in db["quests"].items():
        z = q.get("zoneOrSort")
        if z not in DUNGEONS:
            continue
        rr = q.get("requiredRaces") or 0
        if rr and rr != ALLIANCE and not (rr & NIGHT_ELF):
            continue
        if q.get("requiredClasses"):
            continue
        qid = int(k)
        f = rk.quest(qid)
        if not f:
            continue
        ql, xp = rk.quest_xp_entry(qid) or (f["level"], 0)
        sb = q.get("startedBy")
        giver, spot = None, None
        if isinstance(sb, list) and sb and sb[0]:
            n = db["npcs"].get(str(sb[0][0]))
            giver = n and n.get("name")
        if f["start"]:
            spot = [f["start"][0][0], round(f["start"][0][1], 1), round(f["start"][0][2], 1)]
        out.setdefault(DUNGEONS[z], []).append(
            {
                "id": qid,
                "name": q.get("name"),
                "min": f["min"],
                "level": ql if ql and ql > 0 else f["level"],
                "xp": xp,
                "giver": giver or ("an item" if f["start_item"] else "inside the dungeon"),
                "at": spot,
                "pre": q.get("preQuestSingle") or [],
                "preAll": q.get("preQuestGroup") or [],
            }
        )
    return out


def write(out, path):
    lines = [*HEADER, "DruidKitDungeonData = {"]
    order = sorted(out.items(), key=lambda kv: min(q["min"] for q in kv[1]))
    for name, qs in order:
        lines.append(f"  {{ name = {lua(name)}, quests = {{")
        for q in sorted(qs, key=lambda q: (q["min"], q["id"])):
            fields = ", ".join(f"{k} = {lua(v)}" for k, v in q.items() if v not in (None, []))
            lines.append(f"    {{ {fields} }},")
        lines.append("  } },")
    lines.append("}")
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{sum(len(v) for v in out.values())} quests in {len(out)} dungeons -> {path}")


if __name__ == "__main__":
    write(build(), sys.argv[1] if len(sys.argv) > 1 else HERE.parent / "DruidKit" / "DruidKit_DungeonData.lua")
